import { ButtonType } from './tiles.js';

/** Input state is independent of circuits. Track contacts by contactId. */
export class ButtonController {
  constructor({ onPair = () => {}, onSingle = () => {}, onChange = () => {} } = {}) {
    this.buttons = new Map();
    this.enabled = true;
    this.held = new Map();
    this.blocked = new Set();
    this.mousePresses = new Map();
    this.onPair = onPair;
    this.onSingle = onSingle;
    this.onChange = onChange;
    this.sequence = 0;
    this.listeners = new Set();
  }

  subscribe(listener) { this.listeners.add(listener); return () => this.listeners.delete(listener); }
  #emit(event) { for (const listener of this.listeners) listener(event); }
  #changed(reason = 'press') { this.onChange(); this.#emit(Object.freeze({ kind: 'state', reason, pressedIds: Object.freeze(this.pressedIds) })); }

  register(button) {
    if (!button?.id || this.buttons.has(button.id)) throw new Error('Button ID is empty or duplicated.');
    if (!Object.values(ButtonType).includes(button.type)) throw new Error('Invalid button type.');
    this.buttons.set(button.id, Object.freeze({ ...button }));
  }

  getState(id) {
    const contacts = this.held.get(id);
    return Object.freeze({ pressed: !!contacts?.size, latched: !!contacts?.has('latch') });
  }

  get pressedIds() { return [...this.held.keys()]; }

  isBlocked(id) { return this.blocked.has(id); }

  setEnabled(enabled) {
    if (this.enabled === enabled) return;
    this.enabled = enabled;
    if (!enabled) this.releaseAll();
    this.#changed('switch');
  }

  setBlocked(id, blocked) {
    this.#button(id);
    if (this.blocked.has(id) === blocked) return;
    const wasPressed = this.held.has(id);
    if (blocked) {
      this.blocked.add(id);
      this.held.delete(id);
    } else this.blocked.delete(id);
    this.#changed('blocked');
    if (blocked && wasPressed) this.#emit(this.#event('button-up', [id], 'blocked'));
  }

  /** Mouse and keyboard: latch the first press and release it when pressed again. */
  toggleLatch(id, input = 'mouse') {
    const button = this.#button(id);
    if (this.isBlocked(id)) return false;
    if (button.type !== ButtonType.PAIRED) throw new Error('Single-action buttons cannot be latched.');
    if (this.held.get(id)?.has('latch')) this.#release(id, 'latch', 'cancel');
    else this.#press(id, 'latch', input);
  }

  /** Mouse and phone: the second press issues the paired command and holds both buttons until release. */
  mouseDown(id, contactId, input = 'mouse') {
    const button = this.#button(id);
    if (button.type !== ButtonType.PAIRED) throw new Error('This method is for paired buttons.');
    if (this.isBlocked(id) || this.mousePresses.has(contactId)) return false;
    if (this.held.get(id)?.has('latch')) {
      this.#release(id, 'latch', 'cancel');
      return false;
    }
    const releaseIds = new Set();
    this.mousePresses.set(contactId, { id, releaseIds });
    return this.#press(id, 'latch', input, releaseIds);
  }

  mouseUp(contactId, cancelled = false) {
    const press = this.mousePresses.get(contactId);
    if (!press) return;
    this.mousePresses.delete(contactId);
    if (cancelled) press.releaseIds.add(press.id);
    for (const id of press.releaseIds) this.#release(id, 'latch', cancelled ? 'cancel' : 'release');
  }

  /** Physical press and release for touch, pen and single-action buttons. */
  contactDown(id, contactId, input = 'touch') {
    if (contactId === null || contactId === undefined) throw new Error('A contact ID is required.');
    const token = `contact:${contactId}`;
    for (const [heldId, contacts] of this.held) {
      if (contacts.has(token)) return false;
    }
    return this.#press(id, token, input);
  }

  contactUp(contactId, cancelled = false) {
    const token = `contact:${contactId}`;
    for (const id of [...this.held.keys()]) this.#release(id, token, cancelled ? 'cancel' : 'release');
  }

  /** Handle a single click generated by accessibility tools. */
  pulse(id, input = 'keyboard') {
    const button = this.#button(id);
    if (button.type !== ButtonType.SINGLE) throw new Error('Paired buttons are not momentary controls.');
    const token = `pulse:${++this.sequence}`;
    try { this.#press(id, token, input); }
    finally { this.#release(id, token); }
  }

  releaseAll() {
    this.mousePresses.clear();
    if (!this.held.size) return;
    const released = this.pressedIds;
    this.held.clear();
    this.#changed('cancel');
    for (const id of released) this.#emit(this.#event('button-up', [id], 'release-all'));
  }

  releaseLatches() {
    this.mousePresses.clear();
    for (const id of [...this.held.keys()]) this.#release(id, 'latch', 'cancel');
  }

  #button(id) {
    const button = this.buttons.get(id);
    if (!button) throw new Error(`Unknown button: ${id}`);
    return button;
  }

  #press(id, token, input, deferredMouseRelease = null) {
    const button = this.#button(id);
    if (this.isBlocked(id)) return false;
    const alreadyPressed = this.held.has(id);
    const others = [...this.held.keys()].filter(other => this.buttons.get(other).type === ButtonType.PAIRED && other !== id);
    const contacts = this.held.get(id) ?? new Set();
    if (contacts.has(token)) return false;
    contacts.add(token);
    this.held.set(id, contacts);
    this.#changed();
    if (alreadyPressed) return false;
    this.#emit(this.#event('button-down', [id], input));

    if (button.type === ButtonType.SINGLE) {
      if (this.enabled) this.onSingle(this.#event('single', [id], input));
      return true;
    }

    for (const other of others) {
      if (!this.held.has(id) || !this.held.has(other)) continue;
      const event = this.#event('pair', [other, id], input);
      try { if (this.enabled) this.onPair(event); this.#emit(event); }
      finally {
        if (deferredMouseRelease) {
          deferredMouseRelease.add(other);
          deferredMouseRelease.add(id);
        } else {
          // Preserve physical contacts and release the momentary keyboard/accessibility pair.
          this.#release(other, 'latch');
          this.#release(id, 'latch');
        }
      }
    }
    return true;
  }

  #event(kind, ids, input) {
    return Object.freeze({
      sequence: ++this.sequence,
      kind,
      input,
      buttons: Object.freeze(ids.map(id => this.buttons.get(id))),
      pressedIds: Object.freeze(this.pressedIds),
    });
  }

  #release(id, token, reason = 'release') {
    const contacts = this.held.get(id);
    if (!contacts?.delete(token)) return;
    const released = !contacts.size;
    if (released) this.held.delete(id);
    this.#changed(reason);
    if (released) this.#emit(this.#event('button-up', [id], 'release'));
  }
}
